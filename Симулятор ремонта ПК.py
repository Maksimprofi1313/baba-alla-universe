import time
import os
import random

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

def print_slow(text, delay=0.03):
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()

def play_game():
    clear_screen()
    print("=" * 50)
    print("   СИМУЛЯТОР РЕМОНТА ПК (ВЕРСИЯ 'У МЕНЯ ЛАПКИ')")
    print("=" * 50)
    time.sleep(1)
    
    print_slow("Твой компьютер сломался. Видеокарта RTX 5060 лежит на столе и подозрительно пахнет горелым.")
    print_slow("На столе также лежат: отвертка, молоток, изолента, микроволновка и банка сгущенки.")
    
    health = 100
    sanity = 100
    
    while health > 0 and sanity > 0:
        print(f"\n❤️ Здоровье ПК: {health}% | 🧠 Твоя психика: {sanity}%")
        print("\nВыбери действие:")
        print("1. Попробовать починить видюху отверткой.")
        print("2. Ударить по системнику молотком.")
        print("3. Залить все изолентой.")
        print("4. Съесть сгущенку и позвонить в ДНС.")
        print("5. Засунуть видюху в микроволновку (погреть).")
        print("6. Спросить совета у ИИ (DeepSeek).")
        print("7. Позвонить Бабе Алле.")
        print("8. Прочитать заклинание Рля Штрукдыгдына.")
        print("9. Позвать папу (Mr. Blond), чтобы он помог.")
        print("10. Сдаться и пойти спать.")
        
        choice = input("\nТвой выбор (1-10): ")
        
        if choice == '1':
            print_slow("\nТы пытаешься починить видюху отверткой. Но случайно задеваешь конденсатор.")
            damage = random.randint(10, 30)
            health -= damage
            print(f"💥 Искры! Ты повредил плату на {damage}%.")
            
        elif choice == '2':
            print_slow("\nТы бьешь по системнику молотком. Звук такой, будто ты ломаешь стену.")
            damage = random.randint(20, 50)
            health -= damage
            print(f"🔨 Ты разбил корпус! ПК потерял {damage}% здоровья.")
            
        elif choice == '3':
            print_slow("\nТы заматываешь всё изолентой. Абсолютно всё.")
            print("🩹 Ты чувствуешь себя инженером. Но ПК не включается.")
            sanity -= 10
            
        elif choice == '4':
            print_slow("\nТы съедаешь сгущенку и звонишь в ДНС.")
            print_slow("ДНС: 'А вы пробовали выключить и включить?'")
            sanity -= 20
            print("📞 Ты потерял 20% психики.")
            
        elif choice == '5':
            print_slow("\nТы кладешь видюху в микроволновку и ставишь на 2 минуты.")
            print("💥 БУМ! Микроволновка взорвалась, видюха расплавилась.")
            health = 0
            
        elif choice == '6':
            print_slow("\nТы спрашиваешь у ИИ: 'Как починить видюху?'")
            print_slow("ИИ: 'Сдайте её в сервисный центр по гарантии. Не лезьте внутрь.'")
            sanity += 10
            
        elif choice == '7':
            print_slow("\nТы звонишь Бабе Алле.")
            print_slow("Алла: 'Алло, Идионик? Что случилось? У тебя ПК сломался?'")
            print_slow("Ты: 'Да, бабушка. Видюха сгорела.'")
            print_slow("Алла: 'Ща я приеду на семёрке и мы его взорвем!'")
            if random.random() < 0.5:
                print_slow("Алла приезжает и кидает в системник гранату. ПК уничтожен.")
                health = 0
            else:
                print_slow("Алла приезжает и говорит: 'Да ладно, починим. Где тут у тебя отвертка?'")
                health += 20
                print("🔧 Баба Алла помогла починить ПК (+20% здоровья).")
                
        elif choice == '8':
            print_slow("\nТы читаешь заклинание Рля Штрукдыгдына: 'Рля Штрукдыгдын, приди и почини мой ПК!'")
            print_slow("В комнате становится холодно. Из розетки вырывается красный свет.")
            print_slow("ПК включается! Но теперь он говорит голосом Рля Штрукдыгдына.")
            health += 50
            sanity -= 30
            print("👁️ ПК починен (+50% здоровья), но твоя психика пошатнулась (-30%).")
            
        elif choice == '9':
            print_slow("\nТы зовешь папу. Mr. Blond выходит из комнаты в наушниках.")
            print_slow("Папа: 'Я в CS2 играю, не мешай. Что там у тебя?'")
            print_slow("Ты: 'Видюха сгорела.'")
            print_slow("Папа: 'Ща я её прострелю.'")
            if random.random() < 0.5:
                print_slow("Папа случайно прострелил системник. ПК уничтожен.")
                health = 0
            else:
                print_slow("Папа посмотрел на видюху и сказал: 'Да это гарантийный случай. Завтра отнесем.'")
                sanity += 20
                print("👨 Батя успокоил тебя (+20% психики).")
                
        elif choice == '10':
            print_slow("\nТы сдаешься и идешь спать. На следующий день ты отнес видюху в ДНС.")
            print_slow("Там тебе сказали, что это гарантийный случай, и починили её.")
            print("\n🏁 КОНЦОВКА: МУДРЫЙ ЧЕЛОВЕК. Ты сэкономил нервы и получил рабочую видюху.")
            break
            
        else:
            print_slow("\nТы ничего не выбрал. ПК смотрит на тебя с осуждением.")
        
        if health <= 0:
            print("\n💀 ТВОЙ ПК ВЗОРВАЛСЯ! Ты остался без компа.")
            print("🏁 КОНЦОВКА: ГРУСТНЫЙ ФИНАЛ.")
        elif sanity <= 0:
            print("\n🤯 ТЫ СОШЕЛ С УМА ОТ РЕМОНТА! Тебя забрали в психушку.")
            print("🏁 КОНЦОВКА: ПСИХУШКА.")

def main():
    while True:
        play_game()
        
        print("\n" + "=" * 50)
        print("Что будешь делать дальше?")
        print("1. Начать заново")
        print("2. Выйти")
        
        restart_choice = input("\nТвой выбор (1-2): ")
        
        if restart_choice == '2':
            print("\nСпасибо за игру! Надеюсь, твой ПК когда-нибудь починится.")
            time.sleep(1.5)
            break

if __name__ == "__main__":
    main()