import time
import os
import random

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

def print_slow(text, delay=0.03):
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()

def play_game():
    clear_screen()
    print("=" * 60)
    print("   БИТВА ЗА ВИДЮХУ: ПРОТИВОСТОЯНИЕ С ДНС")
    print("=" * 60)
    time.sleep(1)
    
    print_slow("Ты стоишь в сервисном центре ДНС с запечатанной коробкой.")
    print_slow("Перед тобой менеджер, который явно не хочет принимать твою видюху.")
    
    confidence = 50  # Твоя уверенность (если упадет до 0, ты сдашься)
    manager_anger = 0 # Злость менеджера (если дойдет до 100, он вызовет охрану)
    
    while confidence > 0 and manager_anger < 100:
        print(f"\n💪 Уверенность: {confidence}% | 😡 Злость менеджера: {manager_anger}%")
        print("\nЧто скажешь?")
        print("1. 'По закону о защите прав потребителей я требую замену!'")
        print("2. 'Я снимал на видео, как она свистит! Вот доказательство.'")
        print("3. 'Я знаю, что вы сейчас скажете, что это не гарантийный случай. Но это не так.'")
        print("4. 'Дайте мне жалобную книгу!'")
        print("5. 'Я позову маму, она юрист.'")
        print("6. Сдаться и уйти (выйти из игры).")
        
        choice = input("\nТвой выбор (1-6): ")
        
        if choice == '1':
            print_slow("\nМенеджер: 'Закон о защите прав потребителей? Ха! Вы уверены, что это гарантийный случай?'")
            print_slow("Ты: 'Да, у меня есть заключение сервиса!'")
            print("✅ Ты чувствуешь себя увереннее (+10).")
            confidence += 10
            manager_anger += 5
            
        elif choice == '2':
            print_slow("\nТы показываешь видео. Менеджер смотрит и говорит:")
            print_slow("'Ну, это может быть просто нагрузка. Мы не можем это считать дефектом.'")
            print("❌ Менеджер не верит видео. Твоя уверенность падает (-10).")
            confidence -= 10
            manager_anger += 10
            
        elif choice == '3':
            print_slow("\nТы: 'Я знаю, что вы сейчас скажете, что это не гарантийный случай. Но это не так.'")
            print_slow("Менеджер: 'Откуда вы знаете, что я собирался сказать?'")
            print_slow("Ты: 'Потому что вы всегда так говорите.'")
            print("✅ Ты загнал его в угол! (+15 уверенности).")
            confidence += 15
            manager_anger += 20
            
        elif choice == '4':
            print_slow("\nТы требуешь жалобную книгу. Менеджер нервничает.")
            print_slow("'Хорошо, хорошо. Давайте оформим заявку.'")
            print("✅ Жалобная книга работает! (+20 уверенности).")
            confidence += 20
            manager_anger += 30
            
        elif choice == '5':
            print_slow("\nТы: 'Я позову маму, она юрист.'")
            print_slow("Менеджер: 'Да хоть папу зовите, у нас всё по закону.'")
            if random.random() < 0.5:
                print_slow("Мама приходит и говорит: 'По закону вы обязаны принять товар на проверку.'")
                print("✅ Мама-юрист сработала! (+30 уверенности).")
                confidence += 30
            else:
                print_slow("Мама приходит и говорит: 'Сынок, ну ты чего такой нервный? Давай просто сдадим.'")
                print("❌ Мама не помогла. Твоя уверенность падает (-10).")
                confidence -= 10
            manager_anger += 10
            
        elif choice == '6':
            print_slow("\nТы сдаешься и уходишь. Но на следующий день возвращаешься с папой.")
            print("\n🏁 КОНЦОВКА: ТЫ ВЕРНУЛСЯ. С папой они не спорят.")
            break
            
        else:
            print_slow("\nТы ничего не сказал. Менеджер смотрит на тебя с недоумением.")
            confidence -= 5
            
        if confidence <= 0:
            print("\n😔 ТЫ СДАЛСЯ! Менеджер ухмыляется и говорит: 'Приходите, когда научитесь разговаривать.'")
            print("🏁 КОНЦОВКА: ПОРАЖЕНИЕ.")
        elif manager_anger >= 100:
            print("\n🚨 МЕНЕДЖЕР ВЫЗВАЛ ОХРАНУ! Тебя выводят из магазина.")
            print("🏁 КОНЦОВКА: ОХРАНА.")

def main():
    while True:
        play_game()
        
        print("\n" + "=" * 50)
        print("Что будешь делать дальше?")
        print("1. Начать заново")
        print("2. Выйти")
        
        restart_choice = input("\nТвой выбор (1-2): ")
        
        if restart_choice == '2':
            print("\nСпасибо за игру! Надеюсь, ты выиграешь этот спор.")
            time.sleep(1.5)
            break

if __name__ == "__main__":
    main()