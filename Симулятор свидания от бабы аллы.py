import time
import os

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

def print_slow(text, delay=0.03):
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()

def play_date():
    clear_screen()
    print("=" * 55)
    print("   СИМУЛЯТОР СВИДАНИЯ (ПРИ УЧАСТИИ БАБЫ АЛЛЫ)")
    print("=" * 55)
    time.sleep(1)
    
    print_slow("Ты в кафе. Напротив тебя сидит симпатичная девушка.")
    print_slow("Вы мило общаетесь. Но тут в кафе врывается Баба Алла с бензопилой.")
    
    print("\nЧто ты сделаешь?")
    print("1. Сделать вид, что не знаешь её.")
    print("2. Представить её как свою бабушку.")
    print("3. Спросить: 'Бабушка, а зачем ты бензопилу принесла?'")
    print("4. Убежать вместе с девушкой через окно.")
    print("5. Позвонить папе (Mr. Blond), чтобы он забрал её.")
    
    choice = input("\nТвой выбор (1-5): ")
    
    if choice == '1':
        print_slow("\nТы делаешь вид, что не знаешь её.")
        print_slow("Баба Алла: 'Ах ты, Идионик! Я тебя растила, а ты меня не узнаешь?!'")
        print_slow("Она начинает гоняться за тобой по кафе с бензопилой.")
        print_slow("Девушка в панике убегает. Ты остаешься с Аллой.")
        print("\n🏁 КОНЦОВКА: ПОГОНЯ. Свидание провалено, но ты жив.")
        
    elif choice == '2':
        print_slow("\nТы: 'Знакомься, это моя бабушка.'")
        print_slow("Баба Алла: 'Очень приятно! А вы знали, что он до сих пор писается в постель?'")
        print_slow("Девушка в шоке. Она встает и уходит.")
        print("\n🏁 КОНЦОВКА: ПОЗОР. Баба Алла испортила свидание.")
        
    elif choice == '3':
        print_slow("\nТы: 'Бабушка, а зачем ты бензопилу принесла?'")
        print_slow("Баба Алла: 'Как зачем? Я же говорила, мы идем продавать твои органы в Артондо!'")
        print_slow("Девушка достает телефон и звонит в полицию.")
        print("\n🏁 КОНЦОВКА: АРЕСТ. Тебя забрали за попытку продажи органов.")
        
    elif choice == '4':
        print_slow("\nТы хватаешь девушку за руку и прыгаешь в окно.")
        print_slow("Вы приземляетесь в кусты. Девушка смеется: 'Это было круто!'")
        print_slow("Но тут вы видите, что Баба Алла уже сидит в своей семерке и ждет вас.")
        
        print("\nЧто ты сделаешь?")
        print("1. Сесть в машину к Алле.")
        print("2. Попытаться убежать с девушкой.")
        
        choice4 = input("\nТвой выбор (1-2): ")
        
        if choice4 == '1':
            print_slow("\nВы садитесь в семёрку. Алла: 'Вот это по-нашему! Поехали в Срандручильнинск!'")
            print_slow("Девушка: 'А что там?'")
            print_slow("Алла: 'Ведьмы! Будем приносить его в жертву!'")
            print("\n🏁 КОНЦОВКА: БЕЗУМНОЕ ТРИО. Вы втроем уехали к ведьмам.")
        else:
            print_slow("\nВы бежите от Аллы. Но тут на пути появляется Гнидильда.")
            print_slow("Гнидильда: 'Куда собрались? Ритуал еще не окончен!'")
            print("\n🏁 КОНЦОВКА: ВЕДЬМЫ. Вас поймали и отдали тридцати ведьмам.")
            
    elif choice == '5':
        print_slow("\nТы звонишь папе. Mr. Blond выходит из-за угла в наушниках и с автоматом.")
        print_slow("Папа: 'Я тут в CS2 играю, не мешай. Что случилось?'")
        print_slow("Ты: 'Баба Алла пришла на свидание с бензопилой.'")
        print_slow("Папа: 'А, ну это нормально. Ладно, забирайте её и поехали домой.'")
        print("\n🏁 КОНЦОВКА: СЕМЕЙНЫЙ ПОДРЯД. Свидание закончилось, но папа доволен.")
        
    else:
        print_slow("\nТы ничего не сделал. Баба Алла ушла, а девушка осталась.")
        print("\n🏁 КОНЦОВКА: СКУЧНО. Свидание прошло нормально, но без приключений.")

def main():
    while True:
        play_date()
        
        print("\n" + "=" * 50)
        print("Что будешь делать дальше?")
        print("1. Попробовать другое свидание")
        print("2. Выйти")
        
        choice = input("\nТвой выбор (1-2): ")
        
        if choice == '2':
            print("\nВыход. Удачи в личной жизни!")
            time.sleep(1)
            break

if __name__ == "__main__":
    main()