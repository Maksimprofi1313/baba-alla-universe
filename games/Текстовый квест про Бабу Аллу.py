import time
import os

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

def print_slow(text, delay=0.03):
    for char in text:
        print(char, end='', flush=True)
        time.sleep(delay)
    print()

def play_story():
    """Проигрывает одну сессию игры."""
    clear_screen()
    print("=" * 50)
    print("   БАБА АЛЛА И ПРОКЛЯТИЕ РЛЯ ШТРУКДЫГДЫНА")
    print("=" * 50)
    time.sleep(1)
    
    print_slow("Ты просыпаешься в своей комнате. На часах 3 ночи.")
    print_slow("В углу стоит Баба Алла с бензопилой и смотрит на тебя красными глазами.")
    print_slow("Она говорит: 'Просыпайся, Идионик! Мы едем в Артондо!'")
    
    print("\nЧто ты сделаешь?")
    print("1. Спросить: 'Бабушка, а зачем мы едем в Артондо?'")
    print("2. Попытаться убежать через окно.")
    print("3. Сказать: 'Я готов, бабушка. Поехали.'")
    print("4. Позвать папу (Mr. Blond) на помощь.")
    
    choice = input("\nТвой выбор (1-4): ")
    
    if choice == '1':
        print_slow("\nБаба Алла: 'Мы едем продавать твои органы! Шучу. Или нет...'")
        print_slow("Она хватает тебя за руку и тащит на улицу.")
        print_slow("Вы садитесь в белую семёрку с номерами П000ОХ.")
        print_slow("И тут Алла говорит: 'Держись, Идионик! Мы летим в Срандручильнинск!'")
        
        print("\nЧто ты сделаешь?")
        print("1. Спросить: 'А что такое Срандручильнинск?'")
        print("2. Смириться и включить музыку.")
        print("3. Начать молиться Рля Штрукдыгдыну.")
        
        choice2 = input("\nТвой выбор (1-3): ")
        
        if choice2 == '1':
            print_slow("\nАлла: 'Это город, где живут ведьмы. И где тебя хотят принести в жертву.'")
            print_slow("Ты: 'Бабушка, а можно я просто домой пойду?'")
            print_slow("Алла: 'Нет! Мы уже на полпути!'")
            print("\n🏁 КОНЦОВКА: ЖЕРТВА ВЕДЬМ. Тебя съели тридцать ведьм.")
        elif choice2 == '2':
            print_slow("\nТы включаешь радио. Играет песня 'Пошлю его на небо за звёздочкой'.")
            print_slow("Алла подпевает и улыбается. Кажется, она не так уж и опасна.")
            print("\n🏁 КОНЦОВКА: ДОБРЫЙ КРУИЗ. Вы поели пельменей и вернулись домой.")
        else:
            print_slow("\nТы начинаешь молиться. Баба Алла смотрит на тебя и говорит:")
            print_slow("'Ты что, в секту попал? Прекрати это, мы же в кино едем!'")
            print("\n🏁 КОНЦОВКА: СЕКТА. Алла отвезла тебя в психушку.")
            
    elif choice == '2':
        print_slow("\nТы прыгаешь к окну, но Баба Алла хватает тебя за ногу.")
        print_slow("Алла: 'Куда собрался, Идионик? У нас же ритуал!'")
        print_slow("Она достает из сумки гранату и кидает в окно.")
        
        print("\nЧто ты сделаешь?")
        print("1. Увернуться.")
        print("2. Поймать гранату и кинуть обратно.")
        
        choice3 = input("\nТвой выбор (1-2): ")
        
        if choice3 == '1':
            print_slow("\nТы увернулся, но граната взорвала стену.")
            print_slow("Ты выпрыгиваешь в окно и бежишь. Но тут тебя ловит Гнидильда.")
            print("\n🏁 КОНЦОВКА: ГНИДИЛЬДА. Тебя отдали ведьмам.")
        else:
            print_slow("\nТы ловишь гранату и кидаешь обратно. Взрыв!")
            print_slow("Алла: 'Вот это по-нашему! Ладно, живи.'")
            print("\n🏁 КОНЦОВКА: ГЕРОЙ. Ты спас себя и стал крутым.")
            
    elif choice == '3':
        print_slow("\nБаба Алла: 'Вот это по-нашему! Садись в машину.'")
        print_slow("Вы садитесь в семёрку. Алла включает газ и...")
        print_slow("Вы улетаете в космос. Потому что это же Баба Алла.")
        print_slow("Вы прилетаете на планету Рля Штрукдыгдына.")
        print_slow("Но тут тебя встречает Агафоник с отрубленной рукой.")
        
        print("\nЧто ты сделаешь?")
        print("1. Спросить: 'Агафоник, а ты как тут оказался?'")
        print("2. Дать ему поесть.")
        
        choice4 = input("\nТвой выбор (1-2): ")
        
        if choice4 == '1':
            print_slow("\nАгафоник: 'Меня сюда сослали после того, как Алла пыталась продать мои органы.'")
            print_slow("Ты: 'А я думал, ты на органы в Артондо пошел.'")
            print("\n🏁 КОНЦОВКА: ДВА ИДИОНИКА. Вы с Агафоником основали колонию на планете.")
        else:
            print_slow("\nТы даешь ему пельмени. Агафоник плачет от счастья.")
            print_slow("Алла: 'Ну вот, теперь у нас тут коммунизм.'")
            print("\n🏁 КОНЦОВКА: КОСМИЧЕСКИЙ ПЕЛЬМЕНЬ. Вы едите пельмени на другой планете.")

    elif choice == '4':
        print_slow("\nТы зовешь папу. Mr. Blond выходит из-за угла в наушниках и с автоматом.")
        print_slow("Папа: 'Я тут в CS2 играю, не мешай.'")
        print_slow("Алла: 'А ну-ка, иди сюда, поможешь нам с ритуалом!'")
        print_slow("Папа: 'Ладно, только быстро. У меня раунд.'")
        print("\n🏁 КОНЦОВКА: СЕМЕЙНЫЙ ПОДРЯД. Вы все вместе улетели в космос и играете в CS2 с инопланетянами.")
        
    else:
        print("\n🏁 КОНЦОВКА: СКУЧНЫЙ ВЕЧЕР. Ты остался дома, но Алла забрала твои чипсы.")

def main():
    while True:
        play_story()
        
        print("\n" + "=" * 50)
        print("Что будешь делать дальше?")
        print("1. Начать заново (сыграть другую концовку)")
        print("2. Выйти из игры")
        
        restart_choice = input("\nТвой выбор (1-2): ")
        
        if restart_choice == '2':
            print("\nСпасибо за игру! Баба Алла и Идионик прощаются с тобой.")
            time.sleep(1.5)
            break

if __name__ == "__main__":
    main()