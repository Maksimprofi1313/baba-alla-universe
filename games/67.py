import random
import os
import time

def clear_screen():
    os.system('cls' if os.name == 'nt' else 'clear')

# Части отговорки
intros = [
    "Уважаемая (ый) преподаватель,",
    "Извините, пожалуйста,",
    "Я честно пытался,",
    "Тут такое дело,",
    "Вы не поверите, но",
    "Клянусь, это правда,",
]

reasons = [
    "мой кот случайно взорвал ядерный реактор в Майнкрафте",
    "Баба Алла приехала на семёрке и потребовала ехать в Артондо",
    "папа играл в CS2 и случайно прострелил мой системник",
    "я застрял в SCUM, потому что меня окружили голые китайцы",
    "видеокарта сгорела, а вместе с ней и все мои файлы",
    "Гнидильда украла мою тетрадь, чтобы принести её в жертву",
    "я пытался починить видюху микроволновкой, но стало только хуже",
    "мой телефон взорвался от мема про 67",
    "я весь вечер ловил Рля Штрукдыгдына в своей комнате",
    "ДНС отказался принимать мою гарантию, и я впал в депрессию",
]

consequences = [
    "поэтому я не смог сделать домашку.",
    "и мне было не до этого.",
    "вот такая вот история.",
    "надеюсь на ваше понимание.",
    "я обещаю исправиться к следующему уроку.",
    "но я всё равно готов к уроку морально.",
    "и это не моя вина.",
]

def generate_excuse():
    """Генерирует случайную отговорку."""
    intro = random.choice(intros)
    reason = random.choice(reasons)
    consequence = random.choice(consequences)
    
    return f"{intro} {reason}, {consequence}"

def run_generator():
    clear_screen()
    print("=" * 60)
    print("   ГЕНЕРАТОР ОТГОВОРОК (ДЛЯ ШКОЛЫ И НЕ ТОЛЬКО)")
    print("=" * 60)
    
    print("\nГенерируем отговорку:\n")
    time.sleep(0.5)
    
    excuse = generate_excuse()
    print(f"🗣️ {excuse}")
    
    print("\n" + "=" * 60)

def main():
    while True:
        run_generator()
        
        print("\nЧто будешь делать дальше?")
        print("1. Сгенерировать еще одну")
        print("2. Выйти")
        
        choice = input("\nТвой выбор (1-2): ")
        
        if choice == '2':
            print("\nВыход. Удачи в школе!")
            time.sleep(1)
            break

if __name__ == "__main__":
    main()